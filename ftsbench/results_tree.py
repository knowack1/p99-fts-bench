"""Assemble the results tree and generate each per-chart write-up from records.

Every per-chart README here is built from three artifacts and nothing else: the
chart's sidecar JSON, the headers of the series it was drawn from, and the run
manifests. Prose is not a source. Where an artifact does not carry a field, the
README says `UNRECORDED` rather than filling the gap from memory — a write-up
that invents a tuning parameter is worse than one that admits it was not
recorded, because only the second one can be fixed by rerunning the harness.

Each chart directory follows LAPTOP-RUN-PLAN.md's template: what the chart
claims / how it was measured, with the exact commands / configuration and
tuning / gates that passed / the numbers / confidence tier and caveats / what
changes on enwiki+AWS.

Generated files carry a marker comment. A file without that marker is somebody's
hand-written document and is never overwritten; the generator writes alongside
it and says so.

    python3 -m ftsbench.results_tree \\
        --run-name laptop-simplewiki-2026-08 \\
        --chart id=C3,sidecar=results/c3.json,png=results/c3.png,\\
artifacts=data/c3-*.jsonl,manifests=data/manifest-*.json \\
        --copy-raw
"""
import argparse
import glob
import json
import os
import shutil
import sys
from dataclasses import dataclass
from typing import Any, Iterable, Sequence

UNRECORDED = "UNRECORDED"
GENERATED_MARKER = "<!-- generated by ftsbench.results_tree from the artifacts " \
                   "named below; edits are overwritten -->"
DEFAULT_ROOT = "results"
DEFAULT_INDEX = "README.md"
DEFAULT_SLUGS = {
    "C1": "build-throughput",
    "C2": "time-to-searchable",
    "C3": "write-tail-latency",
    "C4": "resource-usage",
    "C5": "headline-percentiles",
    "C6": "query-matrix",
    "C7": "qps-sweep",
    "C8": "freshness",
}
SPEC_KEYS = ("id", "slug", "sidecar", "png", "artifacts", "manifests")
CONFIG_HEAD_KEYS = ("chosen_file", "repetition_files", "host", "env", "metric",
                    "repetition_metric_values", "repetition_metric_spread")
GATE_KEYS = ("gates", "gates_passed", "checks")
TUNING_HEADER_KEYS = ("refresh_interval", "batch_size", "concurrency", "rate",
                      "rate_per_s", "warmup_s", "duration_s", "poll_interval_s",
                      "sample_interval_s", "max_docs", "index_name", "keyspace")


@dataclass(frozen=True)
class ChartSpec:
    chart_id: str
    slug: str
    sidecar: str
    png: str
    artifacts: tuple[str, ...]
    manifests: tuple[str, ...]

    @property
    def directory(self) -> str:
        return f"{self.chart_id.lower()}-{self.slug}"


@dataclass(frozen=True)
class ChartData:
    spec: ChartSpec
    sidecar: dict[str, Any]
    headers: list[tuple[str, dict[str, Any]]]
    manifests: list[tuple[str, dict[str, Any]]]

    @property
    def configs(self) -> dict[str, Any]:
        return self.sidecar.get("configs", {})

    @property
    def missing(self) -> list[str]:
        absent = [] if self.sidecar else [self.spec.sidecar or "sidecar JSON"]
        if not self.headers:
            absent.append("series artifacts")
        if not self.manifests:
            absent.append("run manifests")
        return absent


def parse_pairs(spec: str) -> dict[str, str]:
    pairs = {}
    for chunk in spec.split(","):
        if not chunk.strip():
            continue
        key, _, value = chunk.partition("=")
        pairs[key.strip()] = value.strip()
    unknown = set(pairs) - set(SPEC_KEYS)
    if unknown:
        raise ValueError(f"unknown --chart key(s): {', '.join(sorted(unknown))}")
    return pairs


def normalize_chart_id(value: str) -> str:
    label = value.strip().upper()
    if not label.startswith("C") or not label[1:].isdigit():
        raise ValueError(f"chart id must look like C3, got {value!r}")
    return label


def parse_chart_spec(spec: str) -> ChartSpec:
    pairs = parse_pairs(spec)
    if "id" not in pairs:
        raise ValueError(f"--chart needs an id=, got {spec!r}")
    chart_id = normalize_chart_id(pairs["id"])
    return ChartSpec(
        chart_id=chart_id,
        slug=pairs.get("slug") or DEFAULT_SLUGS.get(chart_id, "chart"),
        sidecar=pairs.get("sidecar", ""),
        png=pairs.get("png", ""),
        artifacts=tuple(pairs.get("artifacts", "").split("|") if
                        pairs.get("artifacts") else ()),
        manifests=tuple(pairs.get("manifests", "").split("|") if
                        pairs.get("manifests") else ()),
    )


def expand_all(patterns: Sequence[str]) -> list[str]:
    found: list[str] = []
    for pattern in patterns:
        found.extend(sorted(glob.glob(pattern)))
    return sorted(dict.fromkeys(found))


def load_json(path: str) -> dict[str, Any]:
    try:
        with open(path, "r", encoding="utf-8") as handle:
            loaded = json.load(handle)
    except (OSError, json.JSONDecodeError):
        return {}
    return loaded if isinstance(loaded, dict) else {}


def read_header(path: str) -> dict[str, Any]:
    """Only the header line: a series can be hundreds of megabytes and the
    write-up needs its provenance, not its records."""
    try:
        with open(path, "r", encoding="utf-8") as handle:
            for line in handle:
                if not line.strip():
                    continue
                record = json.loads(line)
                return record if record.get("record") == "header" else {}
    except (OSError, json.JSONDecodeError):
        return {}
    return {}


def load_chart(spec: ChartSpec) -> ChartData:
    headers = [(path, read_header(path)) for path in expand_all(spec.artifacts)]
    manifests = [(path, load_json(path)) for path in expand_all(spec.manifests)]
    return ChartData(spec=spec, sidecar=load_json(spec.sidecar) if spec.sidecar
                     else {},
                     headers=[pair for pair in headers if pair[1]],
                     manifests=[pair for pair in manifests if pair[1]])


def render_scalar(value: Any) -> str:
    """Floats arrive at full binary precision from the sidecar; a README showing
    72.17065999999986 hides the digits that matter. The sidecar keeps the exact
    value."""
    if value is None:
        return UNRECORDED
    if isinstance(value, float):
        return f"{value:.6g}"
    return str(value)


def render_value(value: Any) -> str:
    if value is None or value == "" or value == []:
        return UNRECORDED
    if isinstance(value, (list, tuple)):
        return ", ".join(render_scalar(item) for item in value)
    return render_scalar(value)


def value_of(mapping: dict[str, Any], key: str) -> str:
    return render_value(mapping.get(key))


def bullets(items: Iterable[str]) -> str:
    listed = [item for item in items if item]
    return "\n".join(f"- {item}" for item in listed) if listed else f"- {UNRECORDED}"


def table(headers: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    if not rows:
        return f"_{UNRECORDED}_"
    head = f"| {' | '.join(headers)} |\n|{'|'.join(['---'] * len(headers))}|"
    body = "\n".join(f"| {' | '.join(str(cell) for cell in row)} |" for row in rows)
    return f"{head}\n{body}"


def section(title: str, body: str) -> str:
    return f"## {title}\n\n{body}\n"


def flatten(mapping: dict[str, Any], prefix: str = "") -> list[tuple[str, str]]:
    rows: list[tuple[str, str]] = []
    for key, value in mapping.items():
        name = f"{prefix}{key}"
        if isinstance(value, dict):
            rows.extend(flatten(value, f"{name}."))
        else:
            rows.append((name, render_value(value)))
    return rows


def heading(data: ChartData) -> str:
    spec = data.spec
    title = value_of(data.sidecar, "title")
    stamp = value_of(data.sidecar, "preliminary_stamp")
    lines = [GENERATED_MARKER, "", f"# {spec.chart_id} — {title}", "",
             f"**{stamp}**" if stamp != UNRECORDED else f"stamp: {UNRECORDED}", "",
             value_of(data.sidecar, "subtitle")]
    if data.missing:
        lines += ["", f"**Incomplete: no {', no '.join(data.missing)} was found for "
                      f"this chart. Every field below that depended on it reads "
                      f"{UNRECORDED}.**"]
    lines += blank_chart_banner(data.sidecar)
    return "\n".join(lines) + "\n"


def configs_that_drew_nothing(sidecar: dict[str, Any]) -> list[str]:
    """Configs whose every bucket was refused for want of samples.

    A percentile refused per bucket leaves a gap, which is right. A config whose
    every bucket is refused contributes no line at all, and C3 shipped three of
    them under a legend reading "0/28 buckets"."""
    empty = []
    for name, config in (sidecar.get("configs") or {}).items():
        total = config.get("buckets")
        refused = config.get("buckets_without_support") or {}
        if total and refused and min(refused.values()) >= total:
            empty.append(name)
    return empty


def blank_chart_banner(sidecar: dict[str, Any]) -> list[str]:
    empty = configs_that_drew_nothing(sidecar)
    if not empty:
        return []
    return ["", f"**This chart drew nothing for {', '.join(empty)}: every bucket "
                f"held too few operations to carry the percentile. The png is "
                f"axes and a legend. Read the claim below as untested, not as "
                f"refuted, and fix the measurement before re-reading it.**"]


def claim_section(data: ChartData) -> str:
    body = bullets([f"Claim: {value_of(data.sidecar, 'claim')}",
                    f"Assessment: {value_of(data.sidecar, 'claim_status')}"])
    return section("What this chart claims", body)


def manifest_commands(data: ChartData) -> list[str]:
    commands = []
    for path, manifest in data.manifests:
        for command in manifest.get("commands", []) or []:
            commands.append(f"`{command}` — {os.path.basename(path)}")
    return commands


def measurement_section(data: ChartData) -> str:
    plot_command = value_of(data.sidecar, "command")
    parts = [
        "**Commands recorded by the run manifests, in order:**",
        bullets(manifest_commands(data)),
        "",
        "**Plot command recorded in the sidecar:**",
        f"```\n{plot_command}\n```",
        "",
        "**Definitions the chart used:**",
        bullets([f"x axis: {value_of(data.sidecar, 'x_axis')}",
                 f"y axis: {value_of(data.sidecar, 'y_axis')}",
                 f"repetition handling: {value_of(data.sidecar, 'run_selection')}"]),
        "",
        "**Series the chart was drawn from:**",
        bullets([f"`{path}`" for path, _ in data.headers]),
    ]
    return section("How it was measured", "\n".join(parts))


def manifest_versions(data: ChartData, config_name: str) -> str:
    """Every engine component the config's manifests probed, named.

    A ScyllaDB config runs two services, and the series header carries one
    `engine_version` -- the vector-store's, because that is what the sampler
    polls. Reporting it bare under a `scylladb` engine column names the wrong
    component, and the manifests already probed both.
    """
    versions = {}
    for _, manifest in data.manifests:
        if manifest.get("config") != config_name:
            continue
        for engine, probe in (manifest.get("engines", {}) or {}).items():
            version = probe.get("version")
            if version:
                versions[engine] = version
    return ", ".join(f"{engine}={version}"
                     for engine, version in sorted(versions.items()))


def config_version(data: ChartData, name: str, config: dict[str, Any]) -> str:
    return manifest_versions(data, name) or value_of(config, "engine_version")


def config_rows(data: ChartData) -> list[list[str]]:
    rows = []
    for name, config in data.configs.items():
        rows.append([name, value_of(config, "engine"),
                     config_version(data, name, config),
                     value_of(config, "cache_state"),
                     value_of(config, "repetitions"),
                     value_of(config, "corpus"),
                     value_of(config, "max_docs"),
                     value_of(config, "git_commit")])
    return rows


def tuning_rows(data: ChartData) -> list[list[str]]:
    rows = []
    for path, header in data.headers:
        recorded = {key: header[key] for key in TUNING_HEADER_KEYS if key in header}
        rows.append([os.path.basename(path),
                     ", ".join(f"{key}={value}" for key, value in recorded.items())
                     or UNRECORDED])
    return rows


def image_rows(data: ChartData) -> list[list[str]]:
    rows = []
    for path, manifest in data.manifests:
        images = manifest.get("images", {}) or {}
        engines = manifest.get("engines", {}) or {}
        versions = ", ".join(f"{name}={probe.get('version', UNRECORDED)}"
                             for name, probe in engines.items()) or UNRECORDED
        rows.append([os.path.basename(path), value_of(manifest, "config"),
                     ", ".join(images.values()) or UNRECORDED, versions])
    return rows


def configuration_section(data: ChartData) -> str:
    parts = [
        table(["config", "engine", "version", "cache", "N", "corpus", "max_docs",
               "git commit"], config_rows(data)),
        "",
        "**Tuning recorded in each series header:**",
        table(["series", "recorded settings"], tuning_rows(data)),
        "",
        "**Image pins and engine versions recorded in the manifests:**",
        table(["manifest", "config", "images", "engine versions"], image_rows(data)),
    ]
    return section("Configuration and tuning", "\n".join(parts))


def recorded_gates(data: ChartData) -> list[str]:
    found = []
    for path, document in [(data.spec.sidecar, data.sidecar), *data.manifests]:
        for key in GATE_KEYS:
            if document.get(key):
                found.append(f"{os.path.basename(path)} `{key}`: "
                             f"{value_of(document, key)}")
    return found


def gates_section(data: ChartData) -> str:
    gates = recorded_gates(data)
    if gates:
        return section("Gates that passed", bullets(gates))
    searched = ", ".join(GATE_KEYS)
    body = (f"{UNRECORDED} — no artifact for this chart carries a gate record "
            f"(looked for {searched} in the sidecar and every manifest). The "
            f"gates in LAPTOP-RUN-PLAN.md were not machine-recorded, so this "
            f"section cannot state which of them passed.")
    return section("Gates that passed", body)


def metric_rows(data: ChartData) -> list[list[str]]:
    rows = []
    for name, config in data.configs.items():
        spread = config.get("repetition_metric_spread", {}) or {}
        rows.append([name, value_of(config, "metric"),
                     value_of(config, "repetition_metric_values"),
                     value_of(spread, "median"), value_of(spread, "min"),
                     value_of(spread, "max"),
                     f"`{os.path.basename(value_of(config, 'chosen_file'))}`"])
    return rows


def detail_rows(config: dict[str, Any]) -> list[list[str]]:
    detail = {key: value for key, value in config.items()
              if key not in CONFIG_HEAD_KEYS}
    return [[key, value] for key, value in flatten(detail)]


def details_block(data: ChartData) -> str:
    blocks = []
    for name, config in data.configs.items():
        blocks.append(f"<details><summary>{name} — every field the sidecar "
                      f"recorded</summary>\n\n"
                      f"{table(['field', 'value'], detail_rows(config))}\n\n"
                      f"</details>")
    return "\n\n".join(blocks) if blocks else f"_{UNRECORDED}_"


def numbers_section(data: ChartData) -> str:
    parts = [
        "**Per-repetition spread of the metric the median run was chosen by:**",
        table(["config", "metric", "per-repetition values", "median", "min", "max",
               "plotted run"], metric_rows(data)),
        "",
        "**Notes the chart carries in its own footer:**",
        bullets(data.sidecar.get("chart_notes", [])),
        "",
        details_block(data),
    ]
    return section("The numbers", "\n".join(parts))


def confidence_section(data: ChartData) -> str:
    body = bullets([f"Confidence: {value_of(data.sidecar, 'confidence_tier')}",
                    f"Write-path disclosure: "
                    f"{value_of(data.sidecar, 'write_path_disclosure')}",
                    f"Stamp on the image: "
                    f"{value_of(data.sidecar, 'preliminary_stamp')}"])
    return section("Confidence tier and caveats", body)


def aws_section(data: ChartData) -> str:
    return section("What changes on enwiki + AWS",
                   bullets([value_of(data.sidecar, "aws_delta")]))


def host_rows(data: ChartData) -> list[list[str]]:
    if not data.headers:
        return []
    _, header = data.headers[0]
    facts = {**header.get("host", {}), **header.get("env", {})}
    return [[key, value] for key, value in flatten(facts)]


def provenance_section(data: ChartData) -> str:
    parts = [
        "Host and environment as recorded in the first series header "
        f"(`{data.headers[0][0] if data.headers else UNRECORDED}`):",
        "",
        table(["fact", "value"], host_rows(data)),
        "",
        "**Manifests:**",
        bullets([f"`{path}`" for path, _ in data.manifests]),
    ]
    return section("Provenance", "\n".join(parts))


def chart_readme(data: ChartData) -> str:
    sections = [heading(data), claim_section(data), measurement_section(data),
                configuration_section(data), gates_section(data),
                numbers_section(data), confidence_section(data),
                aws_section(data), provenance_section(data)]
    return "\n".join(sections)


def is_generated(path: str) -> bool:
    try:
        with open(path, "r", encoding="utf-8") as handle:
            return GENERATED_MARKER.split("—")[0].strip() in handle.read(600)
    except OSError:
        return False


def alternate_path(path: str) -> str:
    stem, extension = os.path.splitext(path)
    return f"{stem}.generated{extension}"


def write_generated(path: str, text: str) -> str:
    """Never clobber a hand-written file: results/<run>/README.md is somebody's
    document, and an index that overwrites it destroys the run's own framing."""
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    target = path if not os.path.exists(path) or is_generated(path) \
        else alternate_path(path)
    with open(target, "w", encoding="utf-8") as out:
        out.write(text)
    return target


def copy_into(directory: str, source: str) -> str:
    if not source or not os.path.isfile(source):
        return ""
    destination = os.path.join(directory, os.path.basename(source))
    if os.path.abspath(source) != os.path.abspath(destination):
        shutil.copy2(source, destination)
    return destination


def copy_raw(directory: str, data: ChartData) -> list[str]:
    raw = os.path.join(directory, "raw")
    os.makedirs(raw, exist_ok=True)
    sources = [path for path, _ in data.headers] + [path for path, _ in
                                                    data.manifests]
    return [copied for copied in (copy_into(raw, path) for path in sources)
            if copied]


def chart_directory(root: str, run_name: str, spec: ChartSpec) -> str:
    directory = os.path.join(root, run_name, spec.directory)
    os.makedirs(directory, exist_ok=True)
    return directory


def build_chart(root: str, run_name: str, spec: ChartSpec,
                with_raw: bool) -> tuple[ChartData, str]:
    data = load_chart(spec)
    directory = chart_directory(root, run_name, spec)
    copy_into(directory, spec.png)
    copy_into(directory, spec.sidecar)
    if with_raw:
        copy_raw(directory, data)
    written = write_generated(os.path.join(directory, "README.md"),
                              chart_readme(data))
    return data, written


def index_rows(built: list[tuple[ChartData, str]]) -> list[list[str]]:
    rows = []
    for data, written in built:
        status = "generated" if not data.missing \
            else f"incomplete — no {', no '.join(data.missing)}"
        rows.append([data.spec.chart_id, value_of(data.sidecar, "title"),
                     f"[`{data.spec.directory}/`]({data.spec.directory}/"
                     f"{os.path.basename(written)})",
                     value_of(data.sidecar, "confidence_tier"), status])
    return rows


def index_document(run_name: str, built: list[tuple[ChartData, str]]) -> str:
    stamps = {value_of(data.sidecar, "preliminary_stamp") for data, _ in built}
    parts = [
        GENERATED_MARKER, "", f"# Chart index — {run_name}", "",
        bullets(sorted(stamp for stamp in stamps if stamp != UNRECORDED)), "",
        table(["chart", "title", "write-up", "confidence", "status"],
              index_rows(built)),
        "",
        "Each write-up is generated from that chart's sidecar JSON, the headers "
        f"of its series and its run manifests. `{UNRECORDED}` means the field was "
        "not in any of them.",
    ]
    return "\n".join(parts) + "\n"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--run-name", required=True,
                        help="results/<run-name>/ directory to assemble")
    parser.add_argument("--results-root", default=DEFAULT_ROOT)
    parser.add_argument("--chart", action="append", required=True,
                        metavar="id=C3,slug=...,sidecar=...,png=...",
                        help="one chart, as comma-separated key=value pairs; "
                             "artifacts= and manifests= take '|'-separated globs")
    parser.add_argument("--index", default=DEFAULT_INDEX,
                        help="index filename inside the run directory")
    parser.add_argument("--copy-raw", action="store_true",
                        help="copy series and manifests into <chart>/raw/")
    return parser.parse_args()


def report(built: list[tuple[ChartData, str]], index: str) -> None:
    for data, written in built:
        missing = f" ({', '.join(data.missing)} missing)" if data.missing else ""
        print(f"{data.spec.chart_id}: {written}{missing}", file=sys.stderr)
    print(f"index: {index}", file=sys.stderr)


def main() -> int:
    args = parse_args()
    try:
        specs = [parse_chart_spec(spec) for spec in args.chart]
    except ValueError as err:
        print(f"error: {err}", file=sys.stderr)
        return 2
    built = [build_chart(args.results_root, args.run_name, spec, args.copy_raw)
             for spec in specs]
    index = write_generated(
        os.path.join(args.results_root, args.run_name, args.index),
        index_document(args.run_name, built))
    report(built, index)
    return 0


if __name__ == "__main__":
    sys.exit(main())
